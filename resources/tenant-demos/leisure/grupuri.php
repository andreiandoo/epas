                runIntro() {
                    const intro = document.querySelector('[data-intro]');
                    const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
                    if (!intro || reduced) {
                        intro?.classList.add('is-hidden');
                        document.documentElement.classList.remove('reveal-ready');
                        return;
                    }
                    if (window.anime) {
                        window.clearTimeout(window.__groupIntroSafety);
                        anime.timeline({ easing: 'easeOutExpo' })
                            .add({ targets: '[data-intro-word]', translateY: [90, 0], opacity: [0, 1], duration: 850 })
                            .add({ targets: '[data-intro-line]', scaleX: [0, 1], duration: 600 }, '-=430')
                            .add({ targets: '[data-intro-copy]', translateY: [16, 0], opacity: [0, 1], duration: 500 }, '-=360')
                            .add({ targets: intro, opacity: [1, 0], duration: 480, delay: 260, complete: () => {
                                intro.classList.add('is-hidden');
                                document.documentElement.classList.remove('reveal-ready');
                                this.animateHero();
                            }});
                    } else {
                        intro.classList.add('is-hidden');
                        document.documentElement.classList.remove('reveal-ready');
                        this.animateHero();
                    }
                },
