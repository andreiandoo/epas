                observeReveals() {
                    const items = document.querySelectorAll('[data-reveal]');
                    if (!('IntersectionObserver' in window)) {
                        items.forEach(item => { item.style.opacity = '1'; item.style.transform = 'none'; });
                        return;
                    }
                    const observer = new IntersectionObserver(entries => {
                        entries.forEach(entry => {
                            if (!entry.isIntersecting) return;
                            if (window.anime) {
                                anime({ targets: entry.target, opacity: [0, 1], translateY: [32, 0], duration: 780, easing: 'easeOutExpo' });
                            } else {
                                entry.target.style.opacity = '1';
                                entry.target.style.transform = 'none';
                            }
                            observer.unobserve(entry.target);
                        });
                    }, { threshold: .12, rootMargin: '0px 0px -40px 0px' });
                    items.forEach(item => observer.observe(item));
                },
                animateRoute() {
                    const path = document.getElementById('hero-group-route');
                    const marker = document.querySelector('[data-route-marker]');
                    if (!path || !marker || !path.getTotalLength) return;
                    const length = path.getTotalLength();
                    let start = null;
                    const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
                    if (reduced) return;
                    const tick = timestamp => {
                        if (!start) start = timestamp;
                        const progress = ((timestamp - start) % 8500) / 8500;
                        const point = path.getPointAtLength(progress * length);
                        marker.setAttribute('cx', point.x);
                        marker.setAttribute('cy', point.y);
                        requestAnimationFrame(tick);
                    };
                    requestAnimationFrame(tick);
                }
            };
