                    const heroItems = Array.from(document.querySelectorAll('[data-hero]'));
                    const visual = document.querySelector('[data-hero-visual]');
                    if (window.anime) {
                        anime({ targets: heroItems, opacity: [0, 1], translateY: [34, 0], delay: anime.stagger(85), duration: 820, easing: 'easeOutExpo' });
                        if (visual) anime({ targets: visual, opacity: [0, 1], translateX: [54, 0], rotate: [2, 0], duration: 1050, easing: 'easeOutExpo', delay: 150 });
                    } else {
                        heroItems.forEach(item => { item.style.opacity = '1'; item.style.transform = 'none'; });
                        if (visual) { visual.style.opacity = '1'; visual.style.transform = 'none'; }
                    }
